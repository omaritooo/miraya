// Bundles the in-page collector into a string that Node injects into an isolated
// world (DESIGN.md › How does the collector read the page without being fooled by it?).
import { mkdirSync, writeFileSync } from 'node:fs'
import { build } from 'esbuild'

const out = new URL('../src/collector/generated/', import.meta.url)
const result = await build({
  entryPoints: [new URL('../src/collector/page/entry.ts', import.meta.url).pathname],
  bundle: true,
  format: 'iife',
  target: 'chrome120',
  minify: true,
  write: false,
})
const source = result.outputFiles[0].text
mkdirSync(out, { recursive: true })
writeFileSync(
  new URL('source.ts', out),
  `// Generated by scripts/bundle-collector.mjs. Do not edit.\nexport const COLLECTOR_SOURCE = ${JSON.stringify(source)}\n`,
)
console.log(`collector bundled: ${(source.length / 1024).toFixed(1)} KiB`)
